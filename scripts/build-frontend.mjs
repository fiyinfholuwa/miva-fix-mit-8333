import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '..');
const envFile = resolve(projectRoot, 'frontend/.env');
const outputFile = resolve(projectRoot, 'frontend/js/config.js');

function readDotEnv(file) {
  if (!existsSync(file)) return {};

  return Object.fromEntries(
    readFileSync(file, 'utf8')
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(line => line && !line.startsWith('#'))
      .map(line => line.replace(/^export\s+/, ''))
      .map(line => {
        const separator = line.indexOf('=');
        if (separator < 0) return [line, ''];
        const key = line.slice(0, separator).trim();
        let value = line.slice(separator + 1).trim();
        if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
          value = value.slice(1, -1);
        }
        return [key, value];
      })
  );
}

const fileEnv = readDotEnv(envFile);
const apiBase = process.env.MIVAFIX_API_BASE || fileEnv.MIVAFIX_API_BASE || 'https://miva.unifiechat.com/api';

const config = `/* Generated by scripts/build-frontend.mjs. Do not put secrets here. */
window.MIVAFIX_API_BASE = ${JSON.stringify(apiBase)} ||
  (location.hostname === 'localhost' || location.hostname === '127.0.0.1'
    ? 'http://localhost:8000/api'
    : '/api');
`;

mkdirSync(resolve(projectRoot, 'frontend/js'), { recursive: true });
writeFileSync(outputFile, config);
console.log(`Generated ${outputFile}`);
